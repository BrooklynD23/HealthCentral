#!/usr/bin/env python3
"""
Generate docs/INDEX.md — a flat, single-file map of every doc under docs/:
title, a one-line summary, and its outbound links. Not a lint check (doesn't
fail the build); run it manually or alongside `docs_lint.py --link-graph`
whenever the docs corpus changes meaningfully.

Usage:
  python3 scripts/generate_docs_index.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from docs_lint import _markdown_files, _iter_markdown_links  # noqa: E402

_TITLE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
_SKIP_LINE = re.compile(
    r"^\s*(\*\*[A-Za-z ]+:\*\*|>|#|\|.*\||```)"  # metadata fields, banners, headings, tables, fences
)


def _extract_title(text: str) -> str:
    match = _TITLE.search(text)
    return match.group(1).strip() if match else "(untitled)"


def _extract_summary(text: str, max_len: int = 200) -> str:
    """First substantive paragraph after the title — skips metadata fields
    (**Owner:** etc.), historical banners (> ...), and headings."""
    lines = text.splitlines()
    started_body = False
    paragraph: list[str] = []
    for line in lines:
        stripped = line.strip()
        if not started_body:
            if stripped.startswith("# "):
                started_body = True
            continue
        if not stripped:
            if paragraph:
                break
            continue
        if _SKIP_LINE.match(line):
            continue
        paragraph.append(stripped)
    summary = " ".join(paragraph)
    # Rewrite [text](target) to just the text: source-relative link targets
    # don't resolve from docs/INDEX.md and would trip DOC-007.
    summary = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", summary)
    if len(summary) > max_len:
        summary = summary[: max_len - 1].rsplit(" ", 1)[0] + "…"
    return summary or "(no summary — see file)"


def generate(repo_root: Path) -> str:
    forward: dict[str, list[str]] = {}
    for rel_path, _target, resolved_rel in _iter_markdown_links(repo_root):
        if resolved_rel is None or resolved_rel == rel_path:
            continue
        forward.setdefault(rel_path, [])
        if resolved_rel not in forward[rel_path]:
            forward[rel_path].append(resolved_rel)

    entries = []
    for path in _markdown_files(repo_root):
        rel_path = path.relative_to(repo_root).as_posix()
        text = path.read_text(encoding="utf-8", errors="ignore")
        entries.append(
            {
                "path": rel_path,
                "title": _extract_title(text),
                "summary": _extract_summary(text),
                "links": sorted(forward.get(rel_path, [])),
            }
        )
    entries.sort(key=lambda e: e["path"])

    lines = [
        "# Documentation Index",
        "",
        "> Generated by `scripts/generate_docs_index.py` — do not hand-edit; re-run the script instead.",
        "> Flat repo-map: every doc's title, a one-line summary, and its outbound links, so an agent",
        "> (or a human) can get the whole map from one file instead of re-deriving structure each session.",
        "> For reverse links (\"what links here?\"), see `docs/_link_graph.json`",
        "> (`python3 scripts/docs_lint.py --link-graph`).",
        "",
    ]
    for entry in entries:
        lines.append(f"## `{entry['path']}`")
        lines.append("")
        lines.append(f"**{entry['title']}**")
        lines.append("")
        lines.append(entry["summary"])
        if entry["links"]:
            lines.append("")
            lines.append("Links to: " + ", ".join(f"`{link}`" for link in entry["links"]))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    content = generate(repo_root)
    dest = repo_root / "docs" / "INDEX.md"
    dest.write_text(content, encoding="utf-8")
    print(f"Wrote {dest.relative_to(repo_root)} ({content.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
